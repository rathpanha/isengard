#!/usr/bin/env python3
"""Synthesize assets/sounds/agent-done.wav: a soft three-note rising chime.

Warm sine tones with a gentle 2nd harmonic and slow exponential decay (no
inharmonic partials, which is what makes a sound "clink"). Original work,
generated by this script; no third-party audio.
"""
import math, struct, sys, wave

RATE = 32000
NOTES = [(0.00, 440.00), (0.14, 659.25), (0.30, 880.00)]  # A4, E5, A5
LENGTH = 1.5

samples = [0.0] * int(RATE * LENGTH)
for start, freq in NOTES:
    for i in range(int((LENGTH - start) * RATE)):
        t = i / RATE
        attack = min(1.0, t / 0.012)
        env = attack * math.exp(-t * 3.6)
        tone = math.sin(2 * math.pi * freq * t) + 0.18 * math.sin(2 * math.pi * freq * 2 * t)
        samples[int(start * RATE) + i] += 0.34 * env * tone
peak = max(abs(s) for s in samples)
out = sys.argv[1] if len(sys.argv) > 1 else "assets/sounds/agent-done.wav"
with wave.open(out, "wb") as w:
    w.setnchannels(1)
    w.setsampwidth(2)
    w.setframerate(RATE)
    w.writeframes(b"".join(struct.pack("<h", int(32767 * 0.8 * s / peak)) for s in samples))
